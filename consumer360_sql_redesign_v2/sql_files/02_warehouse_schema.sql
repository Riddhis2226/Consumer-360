-- Rebuild all warehouse objects so this pack can migrate the previous V1 schema.
DROP TABLE IF EXISTS dw.fact_sales, dw.fact_transaction_line, dw.dim_customer,
                     dw.dim_product, dw.dim_country, dw.dim_date, dw.country_region,
                     dw.dq_log CASCADE;
CREATE TABLE dw.dim_customer (
    customer_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER UNIQUE,
    is_unknown BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_unknown_customer CHECK ((is_unknown AND customer_id IS NULL) OR (NOT is_unknown AND customer_id IS NOT NULL))
);
CREATE TABLE dw.dim_product (
    product_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    stock_code TEXT NOT NULL UNIQUE,
    description TEXT,
    product_type TEXT NOT NULL CHECK (product_type IN ('merchandise','postage','discount','adjustment','other'))
);
CREATE TABLE dw.dim_country (
    country_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    country TEXT NOT NULL UNIQUE,
    region TEXT NOT NULL CHECK (region IN ('United Kingdom','Europe','Rest of World','Unknown'))
);
CREATE TABLE dw.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    year SMALLINT NOT NULL,
    quarter SMALLINT NOT NULL,
    month SMALLINT NOT NULL,
    month_name TEXT NOT NULL,
    day_of_week SMALLINT NOT NULL,
    is_weekend BOOLEAN NOT NULL,
    is_holiday_season BOOLEAN NOT NULL
);
CREATE TABLE dw.fact_transaction_line (
    transaction_line_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_raw_row_id BIGINT NOT NULL UNIQUE,
    invoice_no TEXT NOT NULL,
    invoice_ts TIMESTAMP NOT NULL,
    date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    customer_key INTEGER NOT NULL REFERENCES dw.dim_customer(customer_key),
    product_key BIGINT NOT NULL REFERENCES dw.dim_product(product_key),
    country_key INTEGER NOT NULL REFERENCES dw.dim_country(country_key),
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(14,4) NOT NULL,
    line_amount NUMERIC(18,4) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    is_return BOOLEAN NOT NULL,
    is_merchandise BOOLEAN NOT NULL,
    source_file TEXT NOT NULL,
    CHECK (quantity <> 0)
);
CREATE INDEX ix_fact_date ON dw.fact_transaction_line(date_key);
CREATE INDEX ix_fact_customer_date ON dw.fact_transaction_line(customer_key, invoice_ts);
CREATE INDEX ix_fact_invoice ON dw.fact_transaction_line(invoice_no);
CREATE INDEX ix_fact_product ON dw.fact_transaction_line(product_key);
CREATE INDEX ix_fact_country ON dw.fact_transaction_line(country_key);
