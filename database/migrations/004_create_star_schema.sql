BEGIN;

-- 1. CUSTOMER DIMENSION
CREATE TABLE analytics.dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(20) UNIQUE,
    country VARCHAR(100),
    country_count INTEGER NOT NULL DEFAULT 0,
    first_purchase_at TIMESTAMP,
    last_purchase_at TIMESTAMP,
    is_unknown BOOLEAN NOT NULL DEFAULT FALSE
);

INSERT INTO analytics.dim_customer (
    customer_key, customer_id, country, country_count, is_unknown
)
OVERRIDING SYSTEM VALUE
VALUES (0, NULL, 'Unknown', 0, TRUE);

WITH customer_country AS (
    SELECT DISTINCT ON (customer_id)
        customer_id,
        country
    FROM analytics.cleaned_transactions_v2
    WHERE customer_id IS NOT NULL
    ORDER BY customer_id, invoice_date DESC, staging_id DESC
),
customer_stats AS (
    SELECT
        customer_id,
        COUNT(DISTINCT NULLIF(TRIM(country), '')) AS country_count,
        MIN(invoice_date) FILTER (
            WHERE transaction_category = 'SALE'
        ) AS first_purchase_at,
        MAX(invoice_date) FILTER (
            WHERE transaction_category = 'SALE'
        ) AS last_purchase_at
    FROM analytics.cleaned_transactions_v2
    WHERE customer_id IS NOT NULL
    GROUP BY customer_id
)
INSERT INTO analytics.dim_customer (
    customer_id, country, country_count,
    first_purchase_at, last_purchase_at
)
SELECT
    s.customer_id,
    cc.country,
    s.country_count,
    s.first_purchase_at,
    s.last_purchase_at
FROM customer_stats s
LEFT JOIN customer_country cc USING (customer_id);

-- 2. PRODUCT DIMENSION
CREATE TABLE analytics.dim_product (
    product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_code VARCHAR(50) UNIQUE,
    canonical_description TEXT,
    product_class VARCHAR(40) NOT NULL,
    is_merchandise BOOLEAN NOT NULL,
    needs_review BOOLEAN NOT NULL DEFAULT FALSE,
    description_variants INTEGER NOT NULL DEFAULT 0,
    first_seen TIMESTAMP,
    last_seen TIMESTAMP,
    is_unknown BOOLEAN NOT NULL DEFAULT FALSE
);

INSERT INTO analytics.dim_product (
    product_key, stock_code, canonical_description,
    product_class, is_merchandise, is_unknown
)
OVERRIDING SYSTEM VALUE
VALUES (0, NULL, 'Unknown', 'UNKNOWN', FALSE, TRUE);

WITH description_counts AS (
    SELECT
        TRIM(stock_code) AS stock_code,
        NULLIF(TRIM(description), '') AS description,
        COUNT(*) AS description_count,
        MAX(invoice_date) AS last_seen
    FROM analytics.cleaned_transactions_v2
    WHERE stock_code IS NOT NULL
      AND NULLIF(TRIM(description), '') IS NOT NULL
    GROUP BY TRIM(stock_code), NULLIF(TRIM(description), '')
),
ranked_descriptions AS (
    SELECT *,
        ROW_NUMBER() OVER (
            PARTITION BY stock_code
            ORDER BY description_count DESC, last_seen DESC, description
        ) AS rn
    FROM description_counts
),
product_stats AS (
    SELECT
        TRIM(stock_code) AS stock_code,
        COUNT(DISTINCT NULLIF(TRIM(description), '')) AS description_variants,
        MIN(invoice_date) AS first_seen,
        MAX(invoice_date) AS last_seen
    FROM analytics.cleaned_transactions_v2
    WHERE stock_code IS NOT NULL
    GROUP BY TRIM(stock_code)
)
INSERT INTO analytics.dim_product (
    stock_code,
    canonical_description,
    product_class,
    is_merchandise,
    needs_review,
    description_variants,
    first_seen,
    last_seen
)
SELECT
    ps.stock_code,
    rd.description,
    CASE
        WHEN UPPER(ps.stock_code) = 'C2'
            THEN 'DELIVERY_CHARGE'
        WHEN UPPER(ps.stock_code) LIKE 'GIFT\_%' ESCAPE '\'
            THEN 'VOUCHER'
        WHEN UPPER(ps.stock_code) = 'AMAZONFEE'
            THEN 'MARKETPLACE_FEE'
        WHEN UPPER(ps.stock_code) IN ('TEST001', 'TEST002')
            THEN 'TEST_TRANSACTION'
        WHEN UPPER(ps.stock_code) IN (
            'B', 'BANK CHARGES', 'D', 'M', 'ADJUST',
            'ADJUST2', 'POST', 'DOT', 'S'
        )
            THEN 'ADJUSTMENT'
        ELSE 'MERCHANDISE'
    END,
    CASE
        WHEN UPPER(ps.stock_code) IN (
            'C2', 'AMAZONFEE', 'TEST001', 'TEST002',
            'B', 'BANK CHARGES', 'D', 'M', 'ADJUST',
            'ADJUST2', 'POST', 'DOT', 'S'
        )
        OR UPPER(ps.stock_code) LIKE 'GIFT\_%' ESCAPE '\'
            THEN FALSE
        ELSE TRUE
    END,
    UPPER(ps.stock_code) = 'PADS',
    ps.description_variants,
    ps.first_seen,
    ps.last_seen
FROM product_stats ps
LEFT JOIN ranked_descriptions rd
    ON rd.stock_code = ps.stock_code
   AND rd.rn = 1;

-- 3. TRANSACTION-LINE FACT TABLE
CREATE TABLE analytics.fact_sales (
    fact_sales_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    staging_id BIGINT NOT NULL UNIQUE
        REFERENCES staging.retail_transactions(staging_id),
    customer_key BIGINT NOT NULL
        REFERENCES analytics.dim_customer(customer_key),
    product_key BIGINT NOT NULL
        REFERENCES analytics.dim_product(product_key),
    invoice VARCHAR(20) NOT NULL,
    invoice_date TIMESTAMP NOT NULL,
    source_category VARCHAR(40) NOT NULL,
    reporting_category VARCHAR(40) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12,4) NOT NULL,
    candidate_line_amount NUMERIC(18,4) NOT NULL,
    merchandise_line_amount NUMERIC(18,4) NOT NULL,
    non_merchandise_line_amount NUMERIC(18,4) NOT NULL,
    source_country VARCHAR(100),
    source_description TEXT,
    is_cancellation BOOLEAN NOT NULL,
    source_file VARCHAR(100) NOT NULL,
    source_row_number BIGINT NOT NULL
);

INSERT INTO analytics.fact_sales (
    staging_id,
    customer_key,
    product_key,
    invoice,
    invoice_date,
    source_category,
    reporting_category,
    quantity,
    unit_price,
    candidate_line_amount,
    merchandise_line_amount,
    non_merchandise_line_amount,
    source_country,
    source_description,
    is_cancellation,
    source_file,
    source_row_number
)
SELECT
    c.staging_id,
    COALESCE(dc.customer_key, 0),
    COALESCE(dp.product_key, 0),
    c.invoice,
    c.invoice_date,
    c.transaction_category,
    CASE
        WHEN c.transaction_category = 'SALE'
             AND dp.product_class <> 'MERCHANDISE'
            THEN dp.product_class
        ELSE c.transaction_category
    END,
    c.quantity,
    c.unit_price,
    c.candidate_line_amount,
    CASE
        WHEN c.transaction_category = 'SALE'
             AND dp.is_merchandise
            THEN c.candidate_line_amount
        ELSE 0
    END,
    CASE
        WHEN c.transaction_category = 'SALE'
             AND NOT dp.is_merchandise
            THEN c.candidate_line_amount
        ELSE 0
    END,
    c.country,
    c.description,
    c.is_cancellation,
    c.source_file,
    c.source_row_number
FROM analytics.cleaned_transactions_v2 c
LEFT JOIN analytics.dim_customer dc
    ON dc.customer_id = c.customer_id
LEFT JOIN analytics.dim_product dp
    ON dp.stock_code = TRIM(c.stock_code);

-- 4. INDEXES
CREATE INDEX idx_fact_sales_customer_date
    ON analytics.fact_sales(customer_key, invoice_date);

CREATE INDEX idx_fact_sales_product_date
    ON analytics.fact_sales(product_key, invoice_date);

CREATE INDEX idx_fact_sales_invoice
    ON analytics.fact_sales(invoice);

CREATE INDEX idx_fact_sales_category
    ON analytics.fact_sales(reporting_category);

CREATE INDEX idx_dim_customer_country
    ON analytics.dim_customer(country);

-- 5. INTEGRITY ASSERTIONS
DO $$
DECLARE
    source_count BIGINT;
    fact_count BIGINT;
    customer_count BIGINT;
    product_count BIGINT;
BEGIN
    SELECT COUNT(*) INTO source_count
    FROM analytics.cleaned_transactions_v2;

    SELECT COUNT(*) INTO fact_count
    FROM analytics.fact_sales;

    SELECT COUNT(*) INTO customer_count
    FROM analytics.dim_customer
    WHERE NOT is_unknown;

    SELECT COUNT(*) INTO product_count
    FROM analytics.dim_product
    WHERE NOT is_unknown;

    IF source_count <> fact_count THEN
        RAISE EXCEPTION
            'Fact count mismatch: source %, fact %',
            source_count, fact_count;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM analytics.fact_sales
        WHERE customer_key IS NULL OR product_key IS NULL
    ) THEN
        RAISE EXCEPTION 'Null dimension key found in fact table';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM analytics.fact_sales f
        LEFT JOIN analytics.dim_customer d
            ON f.customer_key = d.customer_key
        WHERE d.customer_key IS NULL
    ) THEN
        RAISE EXCEPTION 'Customer referential integrity failed';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM analytics.fact_sales f
        LEFT JOIN analytics.dim_product d
            ON f.product_key = d.product_key
        WHERE d.product_key IS NULL
    ) THEN
        RAISE EXCEPTION 'Product referential integrity failed';
    END IF;

    RAISE NOTICE
        'Validated: % fact rows, % customers, % products',
        fact_count, customer_count, product_count;
END $$;

COMMIT;
